let num1 = Number(prompt ("inserisci il primo numero"));
let num2 = Number(prompt ("inserisci il secondo numero"));

let somma = num1 + num2;
let sottrazione = num1 - num2;
let moltiplicazione = num1 * num2;
let divisione = num1 / num2;
let potenza = num1 ** num2;

console.log(`Con i numeri da te scelti, i risultati delle varie operazioni sono: \nsomma = ${somma}, \nsottrazione = ${sottrazione}, \nmoltiplicazione = ${moltiplicazione}, \ndivisione = ${divisione}, \npotenza = ${potenza}`);





